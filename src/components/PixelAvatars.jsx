export function PixelAvatar({ id, size = 64, style = {} }) {
  const av = AVATARS.find(a => a.id === id)
  if (!av) return (
    <div style={{ width:size, height:size, background:'var(--surface)', border:'1px solid var(--border)', display:'flex', alignItems:'center', justifyContent:'center', fontSize: size*0.3, ...style }}>
      ?
    </div>
  )
  return (
    <div
      style={{ width:size, height:size, imageRendering:'pixelated', flexShrink:0, ...style }}
      dangerouslySetInnerHTML={{ __html: av.svg
        .replace('width="16"', `width="${size}"`)
        .replace('height="16"', `height="${size}"`)
      }}
    />
  )
}